"""Fetch the truck's road route from OSRM (open-source routing engine) and write backend/route_data.py.

    .venv\Scripts\python -m tools.fetch_route

Uses the public OSRM demo server (router.project-osrm.org: light use only, no uptime promise), so the result is saved
into the repo and the app never needs OSRM while running. Map data (c) OpenStreetMap contributors (ODbL).
"""
from __future__ import annotations

import json
import math
import sys
import urllib.request
from pathlib import Path

from backend.seed import GEOFENCES

STOPS = ["Shah Alam Depot", "Seremban Cold Store", "Melaka Dock 2", "Johor Bahru Dock 4"]
OSRM = "https://router.project-osrm.org/route/v1/driving/{coords}?overview=full&geometries=geojson&steps=false"
OUT = Path(__file__).resolve().parent.parent / "backend" / "route_data.py"
EPSILON_M = 250  # simplify: drop points that deviate less than this from the line


def _xy(lat: float, lon: float, lat0: float) -> tuple[float, float]:
    return lon * 111_320 * math.cos(math.radians(lat0)), lat * 110_540


def simplify(points: list[tuple[float, float]], eps: float) -> list[tuple[float, float]]:
    """Ramer-Douglas-Peucker on (lat, lon), distances in metres."""
    lat0 = points[len(points) // 2][0]
    pts = [_xy(a, b, lat0) for a, b in points]
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        i, j = stack.pop()
        (x1, y1), (x2, y2) = pts[i], pts[j]
        dx, dy = x2 - x1, y2 - y1
        norm = math.hypot(dx, dy) or 1.0
        best, idx = 0.0, None
        for k in range(i + 1, j):
            d = abs(dy * (pts[k][0] - x1) - dx * (pts[k][1] - y1)) / norm
            if d > best:
                best, idx = d, k
        if idx is not None and best > eps:
            keep[idx] = True
            stack += [(i, idx), (idx, j)]
    return [p for p, k in zip(points, keep) if k]


def main() -> int:
    by_name = {g["name"]: g for g in GEOFENCES}
    coords = ";".join(f"{by_name[n]['lon']},{by_name[n]['lat']}" for n in STOPS)
    req = urllib.request.Request(OSRM.format(coords=coords), headers={"User-Agent": "ColdTrust-hackathon/1.0 (route fetch)"})
    with urllib.request.urlopen(req, timeout=60) as r:
        data = json.loads(r.read())
    if data.get("code") != "Ok":
        print("OSRM said:", data.get("code"), data.get("message"))
        return 1
    route = data["routes"][0]
    full = [(lat, lon) for lon, lat in route["geometry"]["coordinates"]]
    slim = simplify(full, EPSILON_M)
    km = route["distance"] / 1000
    body = (
        '"""Road route Shah Alam -> Johor Bahru, generated by tools/fetch_route.py from OSRM (do not edit by hand).\n\n'
        'Routing: Project OSRM (BSD-2). Map data: (c) OpenStreetMap contributors, ODbL.\n"""\n'
        "from __future__ import annotations\n\n"
        f"ROUTE_STOPS = {STOPS!r}\n"
        f"ROUTE_DISTANCE_KM = {km:.1f}\n"
        f"ROUTE_DURATION_MIN = {route['duration'] / 60:.0f}\n"
        "ROUTE_SOURCE = 'OSRM via router.project-osrm.org; map data OpenStreetMap contributors'\n\n"
        "# (lat, lon)\nROUTE: list[tuple[float, float]] = [\n"
        + "".join(f"    ({a:.5f}, {b:.5f}),\n" for a, b in slim) + "]\n"
    )
    OUT.write_text(body, encoding="utf-8")
    print(f"{len(full)} road points -> {len(slim)} after simplifying; {km:.0f} km, "
          f"{route['duration'] / 3600:.1f} h driving -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
